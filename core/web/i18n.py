"""Interface language of the local web UI.

Chinese is the authoring language: the template in the page code is the key, and the table
below holds the wording of the other language. A template with no entry is shown as written,
so a new page renders in Chinese until its wording is added here; the tests assert that every
template the server can print has an entry (docs/web.md).
"""

import contextvars

LANGUAGES = ("zh", "en")
DEFAULT = "zh"

_html_lang = {"zh": "zh-CN", "en": "en"}

_language = contextvars.ContextVar("web_language", default=DEFAULT)


def current() -> str:
    """The language of the request being answered."""
    return _language.get()


def use(language: str) -> str:
    """Set the language of this request and return it; an unknown name is refused."""
    name = (language or DEFAULT).strip().lower()
    if name not in LANGUAGES:
        raise ValueError(f"lang= is {' or '.join(LANGUAGES)}, not {language!r}")
    _language.set(name)
    return name


def html_lang(language: str | None = None) -> str:
    """The value of the ``html`` element's ``lang`` attribute."""
    return _html_lang[language or current()]


def tr(template: str, *args) -> str:
    """The template in the current language, with the given values filled in."""
    text = ENGLISH.get(template, template) if current() == "en" else template
    return text.format(*args) if args else text


